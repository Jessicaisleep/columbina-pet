/** `单字|误伤词…` 展开成 Map<单字, 误伤词数组> */
const FALSE_FRIEND_MAP: ReadonlyMap<string, readonly string[]> = (() => {
  const m = new Map<string, string[]>();
  for (const line of FALSE_FRIENDS) {
    const parts = line.split('|');
    const key = parts[0];
    // 末尾带"(不误)"的是给人看的标注，不是真词
    const words = parts.slice(1).filter((w) => w !== '' && !w.includes('('));
    if (!m.has(key)) m.set(key, []);
    (m.get(key) as string[]).push(...words);
  }
  return m;
})();

/**
 * 这次命中是不是假的：`w` 出现在 `at`，但它是某个误伤词的一部分。
 * 只在单字/两字这种短词上检查——多字词（"好可爱"）本身就不容易撞。
 */
function isFalseFriend(s: string, at: number, w: string): boolean {
  if (w.length > 1) return false;
  const list = FALSE_FRIEND_MAP.get(w);
  if (!list || list.length === 0) return false;
  for (const bad of list) {
    const inner = bad.indexOf(w);
    if (inner === -1) continue;
    const start = at - inner;
    if (start < 0) continue;
    if (s.startsWith(bad, start)) return true;
  }
  return false;
}

/**
 * 给一句话打标签。
 *
 * 只处理**用户说的话**（宠物自己说的也走同一套，但在 docsOf 里只给 ask 打——
 * 回复的情绪不代表用户的情绪，混进来会让「我不开心」捞到宠物安慰他的话）。
 */
export function tagOf(text: string): MemoryTags {
  const s = typeof text === 'string' ? text : '';
  if (s.trim() === '') return { topics: [], mood: 'neutral', kind: 'statement' };

  const topics: string[] = [];
  for (const [name, words] of TOPIC_LEXICON) {
    for (const w of words) {
      let at = s.indexOf(w);
      let hit = false;
      while (at !== -1) {
        if (!isFalseFriend(s, at, w)) {
          hit = true;
          break;
        }
        at = s.indexOf(w, at + 1);
      }
      if (hit) {
        if (!topics.includes(name)) topics.push(name);
        break; // 同一类目只记一次
      }
    }
  }

  return { topics, mood: moodOf(s), kind: kindOf(s) };
}

function moodOf(s: string): Mood {
  let score = 0;
  for (const w of POSITIVE) {
    let at = s.indexOf(w);
    while (at !== -1) {
      if (!isFalseFriend(s, at, w)) {
        // 前一个字是否定词 → 极性反转
        const prev = at > 0 ? s[at - 1] : '';
        score += NEGATORS.includes(prev) ? -1 : 1;
      }
      at = s.indexOf(w, at + w.length);
    }
  }
  for (const w of NEGATIVE) {
    let at = s.indexOf(w);
    while (at !== -1) {
      if (!isFalseFriend(s, at, w)) {
        const prev = at > 0 ? s[at - 1] : '';
        score += NEGATORS.includes(prev) ? 1 : -1;
      }
      at = s.indexOf(w, at + w.length);
    }
  }
  if (score > 0) return 'pos';
  if (score < 0) return 'neg';
  return 'neutral';
}

function kindOf(s: string): Kind {
  // 顺序：情绪最强 → 约定 → 提问 → 陈述。
  // 「明天见，开心吗」这种既约定又提问的，先按情绪算没意义，
  // 所以情绪要**同时**满足有明显情绪词才抢；否则让给提问/约定。
  if (QUESTION_RE.test(s)) return 'question';
  if (PLAN_RE.test(s)) return 'plan';
  if (EMOTION_RE.test(s)) return 'emotion';
  return 'statement';
}

/**
 * 把标签拼成一段可检索的文本，接在原文后面一起进倒排索引。
 *
 * 为什么要拼进去而不是单独建索引：现有 `buildIndex` 已经做了 IDF 加权
 * 和四道噪声过滤（df 过半不采信、唯一锚点放行等），
 * 把标签当"原文的一部分"喂进去，**立刻就能用上全部这些机制**，
 * 不用重写一套多路融合。代价是标签词和原文词混在一起排序——
 * 但实测下来这反而是对的：用户问"开心的事"，"开心"命中标签、
 * "好可爱"命中原文，两路都在同一次打分里体现，不需要 RRF。
 */
export function tagText(tags: MemoryTags): string {
  const parts: string[] = [];
  if (tags.topics.length > 0) parts.push(tags.topics.join(' '));
  if (tags.mood === 'pos') parts.push('正面 开心 好');
  else if (tags.mood === 'neg') parts.push('负面 难过 烦');
  if (tags.kind === 'plan') parts.push('约定 计划');
  else if (tags.kind === 'emotion') parts.push('情绪 心情');
  return parts.join(' ');
}

/** 全部类目名（给设置页/调试用，导出稳定顺序） */
export function topicNames(): string[] {
  return TOPIC_LEXICON.map(([n]) => n);
}

/* ------------------------------------------------------------------ *
 * 以下：AI 打标 —— 分「同轮搭车」与「后台补标」两条路
 *
 * 用户两句话定了这个设计：
 *   m09143「现在打标签的不是 AI，而是词典。——不交给模型吗？」
 *   m09397「以现在大模型的能力，一边回对话一边给对话打个标签，其实没啥延时」
 *   m09441「以 DEEPSEEK 的速度，TOKEN 吞吐量的速度我认为完全可以同时进行」
 *
 * 他说得对，而且第一版我做错了：一开始只做了**后台补标**（另发一次请求，
 * 等聊天回复完再跑）。那等于把一次调用拆成两次，多一次往返、多一次排队，
 * 而标签本来就是"这句话在讲什么"，**模型在生成回复时对这句话的理解最完整**，
 * 拆到后面单独问一遍反而丢了上下文。
 *
 * 所以主路改成「同轮搭车」：让模型在回复末尾附一个 `[标:话题|情绪|语气]`，
 * host 解析后剥掉标记再给用户看。机制与配图 `[图:名称]` 完全同构——
 * 那条已经在线上跑了很久，解析/校验/失败原样保留都有现成口径，不必另发明一套。
 *
 * 三条路的分工：
 *   词典    同步、0.05ms、离线可用、不落盘 —— 永远兜底
 *   同轮搭车 与回复同一次生成、零额外往返 —— 主路（模型可用时）
 *   后台补标 历史消息回填（老消息没有标记）—— 补路
 * ------------------------------------------------------------------ */

/** 一次补标最多塞几条原文（太多会让模型偷懒只回前几条） */
export const AI_TAG_BATCH = 20;

/**
 * 同轮打标的指令：追加在 user 正文末尾，紧邻回答位置（与 `imageInstruction` 同一做法）。
 *
 * 为什么带固定类目表：不让它自由发挥，标签才能复用、能聚合；
 * 每条消息都出新类目等于没有分类。但留 `自创` 出口给确实不在表里的情况。
 *
 * 为什么要求"拿不准就留空"：瞎编的标签比没有标签更糟——检索时会把
 * 完全不相关的事捞出来，而且错误会被落盘固化。
 */
export function tagInstruction(): string {
  return (
    '\n\n[打标] 回完这句话后，另起一行附一个标签，说明**用户这句话**在讲什么事：\n' +
    `  [标:话题|情绪|语气]\n` +
    `  话题（0~3 个，用顿号隔开）：优先从这些里选 ${topicNames().join('、')}；都不合适可自创 2~4 字。\n` +
    '  情绪（单选）：pos（正面）/ neg（负面）/ neutral（中性）。看说话人自己的情绪，不要看话里有没有正面词。\n' +
    '  语气（单选）：statement（陈述）/ question（提问）/ plan（约定、计划）/ emotion（情绪表达）。\n' +
    '  例子：用户说「今天出门看见一只毛茸茸的小东西好可爱」→ [标:宠物|pos|emotion]\n' +
    '  拿不准就写 [标:||]，**不要猜**。标签是给记忆库用的，不会展示给用户。'
  );
}

/** 打标标记：`[标:话题|情绪|语气]`（容忍全角冒号/竖线、前后空白、结尾位置） */
const TAG_MARK = /\[标[:：]\s*([^\]\n]*?)\s*\]\s*$/;

/**
 * 从模型回复里取标签（同轮打标的解析半侧；纯函数）。
 *
 * 与 `parseAiTags` 的分工：那个解析**批量**补标的 JSON 数组，这个解析**单条**
 * 内联标记。两者输出形状相同，最终都进 `mergeTags`。
 *
 * 失败一律返回 `{ text }` 原样——**解析失败绝不能吞掉回复**，
 * 这是配图那条路已经验证过的口径（`extractChatImage`）。
 * 唯一会剥除标记的情况：标记格式对得上（即模型确实按要求给了），
 * 此时哪怕内容解析不出标签也要剥——否则用户会看到一行没意义的 `[标:...]`。
 */
export function extractAiTags(text: string): { text: string; tags?: MemoryTags } {
  const s = typeof text === 'string' ? text : '';
  const m = TAG_MARK.exec(s);
  if (!m) return { text: s };
  const body = s.slice(0, m.index).trim();
  // 只回了标记、没有正文 → 判定为生成失败，不剥（交给上层按空正文处理）
  if (body === '') return { text: s };
  const tags = parseTagMark(m[1] ?? '');
  return tags ? { text: body, tags } : { text: body };
}

/**
 * 解析 `话题|情绪|语气` 三段。
 *
 * 容错（都会遇到）：
 *   - 只给两段 → 第三段按陈述
 *   - 情绪/语气大小写混写、写成中文（"正面"）→ 一律归一
 *   - 话题用了逗号/斜杠分隔 → 一起当分隔符
 * 全空（`||`，模型明说拿不准）→ 返回 undefined，让词典兜底，
 * **不要**返回一个"空标签"把词典结果覆盖成空。
 */
function parseTagMark(inner: string): MemoryTags | undefined {
  const parts = String(inner ?? '').split(/[|｜]/);
  const topicsRaw = (parts[0] ?? '').trim();
  const moodRaw = (parts[1] ?? '').trim().toLowerCase();
  const kindRaw = (parts[2] ?? '').trim().toLowerCase();

  const topics: string[] = [];
  if (topicsRaw !== '') {
    for (const t of topicsRaw.split(/[、,，/／\s]+/)) {
      const v = t.trim().slice(0, 8);
      if (v !== '' && !topics.includes(v)) topics.push(v);
      if (topics.length >= 3) break;
    }
  }

  const mood: Mood =
    moodRaw === 'pos' || moodRaw === 'positive' || moodRaw === '正面'
      ? 'pos'
      : moodRaw === 'neg' || moodRaw === 'negative' || moodRaw === '负面'
        ? 'neg'
        : 'neutral';

  const kind: Kind =
    kindRaw === 'question' || kindRaw === '提问'
      ? 'question'
      : kindRaw === 'plan' || kindRaw === '约定' || kindRaw === '计划'
        ? 'plan'
        : kindRaw === 'emotion' || kindRaw === '情绪'
          ? 'emotion'
          : 'statement';

  if (topics.length === 0 && mood === 'neutral' && kind === 'statement') return undefined;
  return { topics, mood, kind };
}

/**
 * 拼 AI 补标的 prompt。
 *
 * 三个刻意的写法：
 *  1. **给固定类目表**再允许它自创：不让它自由发挥，是为了让标签能复用、能聚合——
 *     每条消息都出新类目等于没有分类。留 `custom` 出口是给"确实不在表里"的情况。
 *  2. **要求输出裸 JSON 数组**，并且明说「不要解释」：实测模型很爱在 JSON 前后加
 *     "好的，以下是标签："，解析会失败。
 *  3. **显式允许"拿不准就留空"**：逼它给答案会催生瞎编的标签，
 *     瞎编的标签比没有标签更糟——检索时会把完全不相关的事捞出来。
 */
export function aiTagPrompt(texts: ReadonlyArray<string>): string {
  const list = Array.isArray(texts) ? texts : [];
  return (
    '你是一个给对话片段打标签的工具。下面是若干句用户说的话，给每一句打三个标签。\n\n' +
    '一、topics（话题，可多选，0~3 个）。优先从这些已有类目里选：\n' +
    `  ${topicNames().join('、')}\n` +
    '  如果确实都不合适，可以自创一个 2~4 字的类目名。\n' +
    '  注意：类目是"这句话在讲什么事"，不是"这句话里出现了哪个词"。\n' +
    '  例如"今天出门看见一只毛茸茸的小东西好可爱"——讲的是宠物，不是"出门"。\n\n' +
    '二、mood（情绪，单选）：pos（正面）/ neg（负面）/ neutral（中性）。\n' +
    '  看说话人自己的情绪，不要看话里有没有正面词。\n' +
    '  例如"还行吧""就那样"偏 neutral 甚至 neg，不是 pos。\n' +
    '  例如"累死了""绷不住了"是 neg。\n\n' +
    '三、kind（语气，单选）：statement（陈述）/ question（提问）/ plan（约定、计划）/ emotion（情绪表达）。\n\n' +
    '输出要求：只输出一个 JSON 数组，不要任何解释文字，不要代码块标记。\n' +
    '数组长度必须等于输入句数，第 i 个对象对应第 i 句。\n' +
    '拿不准的字段就留空（topics 给 []，mood 给 "neutral"，kind 给 "statement"），**不要猜**。\n\n' +
    '格式示例：\n' +
    '[{"topics":["宠物"],"mood":"pos","kind":"statement"},{"topics":[],"mood":"neutral","kind":"statement"}]\n\n' +
    '输入（共 ' +
    list.length +
    ' 句）：\n' +
    list.map((t, i) => `${i + 1}. ${t}`).join('\n')
  );
}

/**
 * 解析模型返回的标签数组。
 *
 * 必须容忍的脏输出（都是实测见过的）：
 *   - 前后带说明文字：「好的，以下是标签：」+ JSON
 *   - 包在代码块里：```json ... ```
 *   - 少给几条（模型偷懒）→ 按**位置**对不上就不认，宁可留空也不串位
 *   - 类目拼错 / 大写成 POS
 *
 * 关键取舍：**数量对不上就整体作废**。串位比没有标签坏得多——
 * 张三的"烦"被标到李四的"开心"上，等于给记忆库下毒。
 */
export function parseAiTags(raw: string, expected: number): Array<MemoryTags | undefined> {
  const n = Math.max(0, Math.floor(Number(expected) || 0));
  if (n === 0) return [];
  const text = typeof raw === 'string' ? raw : '';
  const start = text.indexOf('[');
  const end = text.lastIndexOf(']');
  if (start === -1 || end === -1 || end <= start) return new Array(n).fill(undefined);

  let arr: unknown;
  try {
    arr = JSON.parse(text.slice(start, end + 1));
  } catch {
    return new Array(n).fill(undefined);
  }
  if (!Array.isArray(arr) || arr.length !== n) return new Array(n).fill(undefined);

  return arr.map((item) => {
    if (typeof item !== 'object' || item === null) return undefined;
    const o = item as Record<string, unknown>;

    const topicsRaw = Array.isArray(o.topics) ? o.topics : [];
    const topics: string[] = [];
    for (const t of topicsRaw) {
      if (typeof t !== 'string') continue;
      const v = t.trim().slice(0, 8);
      if (v !== '' && !topics.includes(v)) topics.push(v);
      if (topics.length >= 3) break;
    }

    const moodRaw = typeof o.mood === 'string' ? o.mood.trim().toLowerCase() : '';
    const mood: Mood = moodRaw === 'pos' || moodRaw === 'neg' ? moodRaw : 'neutral';

    const kindRaw = typeof o.kind === 'string' ? o.kind.trim().toLowerCase() : '';
    const kind: Kind = kindRaw === 'question' || kindRaw === 'plan' || kindRaw === 'emotion' ? kindRaw : 'statement';

    return { topics, mood, kind };
  });
}

/**
 * 合并两个来源的标签：**AI 优先，词典兜底**。
 *
 * 为什么不直接取 AI 的：AI 可能只给了 topics 但 mood 留了 neutral（"拿不准就留空"），
 * 而词典那边可能明确判出了 pos。这时候词典的信息是有用的，不该丢。
 * 反过来 topics 必须**以 AI 为准**：词典只会命中 10 个类目里的一个，
 * AI 看出"毛茸茸的小东西"是宠物，这是词典做不到的，不能被词典结果污染。
 */
export function mergeTags(lexicon: MemoryTags, ai: MemoryTags | undefined): MemoryTags {
  if (!ai) return lexicon;
  const topics = ai.topics.length > 0 ? ai.topics : lexicon.topics;
  const mood = ai.mood !== 'neutral' ? ai.mood : lexicon.mood;
  const kind = ai.kind !== 'statement' ? ai.kind : lexicon.kind;
  return { topics, mood, kind };
}
